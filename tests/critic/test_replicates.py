"""Critic round 2: multi-history checks that replace the single-dataset D2/D8 tests.

Rebuttal accepted (see docs/CRITIC_LOG.md, Round 2): every lot in one dataset shares one fitted model, so per-dataset
coverage and band bias are one correlated draw, not 1,000 independent trials. The sound test is across independent
histories from the same world: (a) the mean band bias must be within sampling error of zero, (b) the bootstrap
spread must match the TRUE sampling spread of each lot's prediction across histories, and (c) mean coverage must not
collapse. Histories use seeds 71000+ (not used by the builder's report, which used 9000+).
n_boot = n_draws = 20 so each draw is a distinct bootstrap member (see R2-6 on duplicated draws).
"""
import numpy as np
import pandas as pd
import pytest

from src.data.generate import HIST_DATES, HIST_WEIGHTS, simulate_world
from src.model import risk as R
from tests.critic.conftest import arrivals_only

K, NB = 6, 20
BANDS = [0, 500, 600, 700, 800, 2000]


@pytest.fixture(scope="module")
def replicates(cfg):
    f = simulate_world(600, 778, cfg, meta_probs=(0.0, 0.0))
    A = arrivals_only(f)
    mp = f["_marg_p0"].to_numpy()
    band = pd.cut(f["arrival_weight_lb"], BANDS, right=False)
    P, S, cov, bias = [], [], [], []
    for s in range(K):
        h = simulate_world(1400, 71_000 + s, cfg, dates=HIST_DATES, weights=HIST_WEIGHTS, prefix="H")
        m = R.fit(h, n_boot=NB, seed=0)
        r, D = R.assess(m, A, cfg, n_draws=NB)
        p = r["risk_mean"].to_numpy()
        P.append(p)
        S.append(D.std(axis=1, ddof=1))
        cov.append(np.mean((r["risk_lo"].to_numpy() <= mp) & (mp <= r["risk_hi"].to_numpy())))
        bias.append(pd.Series(p - mp).groupby(band, observed=True).mean())
    return {"P": np.array(P), "S": np.array(S), "cov": np.array(cov), "bias": pd.DataFrame(bias),
            "n_band": band.value_counts(), "mp": mp,
            "complete": ~A[R.IMPUTABLE].isna().any(axis=1).to_numpy()}


@pytest.mark.slow
def test_untreated_risk_unbiased_across_histories(replicates):
    """D8 (rewritten). Mean over K histories of (predicted - true E[p|x]) per weight band must be within
    2.5 standard errors + 0.25 pp of zero for every band with >= 100 lots. A systematic bias of the round-1 size
    (-1.4 pp in 600-700 lb, SE there ~0.5 pp with K=6) still fails."""
    b = replicates["bias"]
    se = b.std(ddof=1) / np.sqrt(len(b))
    keep = [c for c in b.columns if replicates["n_band"][c] >= 100]
    bad = {str(c): (round(100 * b[c].mean(), 2), round(100 * se[c], 2)) for c in keep
           if abs(b[c].mean()) > 2.5 * se[c] + 0.0025}
    assert not bad, f"band: (mean bias pp, SE pp) {bad}"


@pytest.mark.slow
def test_bootstrap_spread_matches_sampling_spread(replicates):
    """D2 (rewritten, the sharp version). The 90% range claims each lot's prediction would vary across datasets by
    about the bootstrap SD. Check it: across-history SD of each lot's prediction / mean bootstrap SD must be
    <= 1.25 (median over lots). Round-2 probe (10 histories): 1.06 median, 1.11 head-mean."""
    emp = replicates["P"].std(axis=0, ddof=1)
    boot = replicates["S"].mean(axis=0)
    ratio = float(np.median(emp / boot))
    assert ratio <= 1.25, ratio


@pytest.mark.slow
def test_mean_coverage_across_histories(replicates):
    """D2 (rewritten). Mean coverage of the true E[p|x] over K histories >= 0.83. Nominal is 0.90; the round-2
    probes give 0.85 (10 histories, seeds 70000+) and 0.88 (builder, 8 histories), so the honest claim is
    'about 85-88%' (see R2-6). This bar still catches the round-1 failure (0.77-0.80)."""
    assert replicates["cov"].mean() >= 0.83, replicates["cov"].round(3).tolist()


@pytest.mark.slow
def test_lot_level_misspecification_bias_small(replicates):
    """R2-2. Band means cancel, but the round-2 probe found 20% of lots whose mean prediction over 10 histories is
    > 2 SE from the truth (about 8% expected under no bias): a lot-level bias that resampling cannot see. Pattern
    (scripts/critic/probe_r2_misspec.py): predictions are pulled toward the average lot (+0.5 pp for truly low-risk
    lots, -1.0 pp at 30-50% true risk; auction, high-weather and crowded lots under-predicted), i.e. a logistic
    fit with L2 penalty to data generated by a random-intercept model. Measured on COMPLETE-data lots only (for
    lots with missing fields the simulator's _marg_p0 conditions on values the model never sees, see R2-9), and
    de-noised: RMS_bias^2 = mean_lots[(mean_k p - truth)^2 - var_k(p)/K].
    Acceptance: RMS bias <= 0.5 x mean bootstrap SD on the same lots (then the bias costs the 90% range at most
    ~3 points of coverage)."""
    c = replicates["complete"]
    P, mp = replicates["P"][:, c], replicates["mp"][c]
    mb2 = (P.mean(axis=0) - mp) ** 2 - P.var(axis=0, ddof=1) / len(P)
    rms = float(np.sqrt(max(mb2.mean(), 0.0)))
    boot = float(replicates["S"][:, c].mean())
    print(f"complete lots n={c.sum()}: de-noised RMS lot-level bias {100 * rms:.2f} pp; mean bootstrap SD {100 * boot:.2f} pp")
    assert rms <= 0.5 * boot, (round(rms, 4), round(boot, 4))
